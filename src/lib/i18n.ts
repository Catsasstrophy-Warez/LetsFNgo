export type MsgKey = keyof typeof en;


const DICTS: Record<Lang, Partial<Record<MsgKey, string>>> = { en, es: {} };
const loaded = new Set<Lang>(['en']);

/** Install a language dictionary (the Spanish one is a separate chunk, loaded on demand). */
export function registerLang(lang: Lang, dict: Partial<Record<MsgKey, string>>): void { DICTS[lang] = dict; loaded.add(lang); }
export const isLangLoaded = (lang: Lang) => loaded.has(lang);
/** Load a language's dictionary chunk once. Until it arrives, `translate` falls back to English. */
export async function loadLang(lang: Lang): Promise<void> {
  if (loaded.has(lang)) return;
  if (lang === 'es') registerLang('es', (await import('./i18n-es')).es);
}

export const normLang = (v: unknown): Lang => (v === 'es' ? 'es' : 'en');

/** Translate a key, falling back to English. `{name}` placeholders are filled from `vars`; `{n|one|other}` picks a plural form. */
export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  if (!vars) return s;
  // Plurals: {n|lap|laps} picks the singular when vars.n === 1.
  return s.replace(/\{(\w+)\|([^|{}]*)\|([^|{}]*)\}/g, (m, k, one, other) => (k in vars ? (Number(vars[k]) === 1 ? one : other) : m))
    .replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

let current: Lang = 'en';
/** Language for pure helpers that cannot use the React context (e.g. `fmt`). App sets it on every render. */
export const setCurrentLang = (l: Lang) => { current = l; };
export const currentLang = () => current;
/** Translate with the current app language (for non-React helpers). */
export const tr = (key: MsgKey, vars?: Record<string, string | number>) => translate(current, key, vars);

/** Keys a language has not translated yet (English is always complete by construction). */
export const missingKeys = (lang: Lang): MsgKey[] => (Object.keys(en) as MsgKey[]).filter((k) => !DICTS[lang][k]);
